"""Shared evidence requirements for every simulation-authoring stage."""

EVIDENCE_PLANNING_GUIDELINES = '''Assumption and outcome provenance (assumption-outcome-evidence.v1) applies to every simulation domain,
including tokens, DeFi, governance, adoption and nonfinancial decisions. For EVERY material numerical
or behavioral assumption and its modeled consequences, retain an input -> mechanism -> outcome chain.
Each claim needs either a reviewed, specific real-life reference or a documented reasonable cause;
a reputable homepage, a persona biography or an unsupported model number is not sufficient.
Record source publisher/locator, measured definition, units/population/window, publication/availability
and capture times, uncertainty, permitted use and limitations. Review source authenticity, incentives,
coverage, market liquidity/poll methodology and material disagreement, not just its name.
Every causal transfer needs a formula/rule or an explicit bounded hypothesis, sensitivity comparison
and falsification condition. Paid exposure can change observations, not guarantee demand or uplift.
An outcome inherits its inputs' uncertainty; an assumed conversion does not become observed by being
calculated or by being repeated across thousands of model calls. Unknowns block dependent readiness.
Keep official resolved votes/results, polls, expert forecasts, prediction-market quotes, historical
frequencies, model action scores and simulated frequencies distinct: poll shares are not event probabilities.
A prediction-market reference needs the exact contract, resolution rules, quote time, liquidity,
spread and fees; a poll needs population, sample/method and fieldwork dates. Any transfer to another
event, horizon, population or token-price response needs its own reviewed causal/calibration claim.
Forecasts are comparisons, not targets to force simulated outcomes to match. Research as of the
decision cutoff; later captures are not independently archived prior knowledge. Retain disagreements,
failed predictions and out-of-sample outcomes. A scheduled session is not a known vote outcome.
Use a sidecar evidence register and reviewed target inventory; never add fields to strict world schemas.
The offline evidence audit checks provenance structure and dependency coverage, not source truth or
scientific validity. Keep ungrounded dependent inputs/results incomplete under the caller's contract;
do not publish calibrated odds, an optimum or a ready world to hide the evidence gap.'''
